export const attackCardSchema = z.object({
  family: z.string(),
  title: z.string(),
  variants: z.array(z.string()).length(4),
  channel: z.string(),
  rail: z.string(),
  genai_enabler: z.string(),
  objective: z.string(),
  event_sequence: z.array(z.string()),
  amount_range: z.tuple([z.number(), z.number()]),
  event_range: z.tuple([z.number(), z.number()]),
  base_risk: z.number(),
  device_reuse: z.number(),
  beneficiary_reuse: z.number(),
  merchant_risk: z.number(),
  velocity: z.number(),
  novelty: z.number(),
  mitigations: z.array(z.string()),
});

export const calibrationSchema = z.object({
  calibration_split: z.string(),
  evaluation_split: z.string(),
  legitimate_split_rows: z.object({ train: z.number(), validation: z.number(), test: z.number() }),
  event_id_overlap_validation_test: z.number(),
  known_campaign_overlap_train_validation: z.number(),
  known_campaign_overlap_validation_test: z.number(),
  held_out_campaigns_generated_separately: z.boolean(),
  thresholds: z.record(z.string(), z.object({
    source: z.string(),
    legitimate_rows: z.number(),
    target_fpr: z.number(),
    empirical_validation_fpr: z.number(),
    threshold: z.number(),
  })),
  test_rows_used_for_threshold_selection: z.boolean(),
});

