export const representativeCampaignSchema = z.object({
  artifact_version: z.string(),
  artifact_type: z.literal("representative_campaign_rollout"),
  evidence_boundary: z.string(),
  selection_note: z.string(),
  generator: z.object({
    implementation: z.string(),
    simulator_design: z.literal("hand-coded_stateful_entity_linked"),
    config_path: z.string(),
    world_seed: z.number(),
    action_seed: z.number(),
    campaign_seed: z.number(),
  }),
  attack_card: attackCardSchema,
  action: z.record(z.string(), z.union([z.string(), z.number()])),
  fidelity: fidelitySchema,
  summary: z.object({
    campaign_id: z.string(),
    event_count: z.number(),
    start_timestamp: z.string(),
    end_timestamp: z.string(),
    duration_minutes: z.number(),
    unique_customers: z.number(),
    unique_devices: z.number(),
    unique_merchants: z.number(),
    unique_beneficiaries: z.number(),
    maximum_velocity_10m: z.number(),
    maximum_velocity_1h: z.number(),
    maximum_graph_shared_entities: z.number(),
  }),
  events: z.array(campaignEventSchema).min(1),
});

export type Aggregate = z.infer<typeof aggregateSchema>;
