import { z } from "zod";

const metricSummarySchema = z.object({
  mean: z.number(),
  std: z.number(),
  ci95_low: z.number(),
  ci95_high: z.number(),
  min: z.number(),
  max: z.number(),
  n: z.number(),
});

const testSchema = z.object({
  test: z.string(),
  statistic: z.number(),
}).passthrough();

